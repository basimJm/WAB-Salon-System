import { Router, type Request, type RequestHandler, type Response } from 'express';
import type { z } from 'zod';
import { UPLOAD_ROUTES } from '../../../constants/uploads';
import type { UploadActor, UploadsService } from '../../../domain/uploads/uploads.service';
import { validate } from '../../../middlewares/validate';
import { asyncHandler } from '../../../utils/async';
import { sendSuccess } from '../../../utils/response/successResponse';
import { confirmSchema, licensePresignSchema, presignSchema } from './uploads.validation';

export interface UploadsRouterOptions {
  readonly service: UploadsService;
  /** Authentication for the signed-in routes (empty for none). */
  readonly guard: readonly RequestHandler[];
  readonly actorOf: (req: Request) => UploadActor;
  /** Per-IP limiter; used on the public license routes. */
  readonly limiter: RequestHandler;
  /** Offer the public (guest) license-document routes of the merchant app. */
  readonly guestLicense?: boolean;
}

const GUEST: UploadActor = { scope: 'guest', ownerType: 'GUEST', ownerId: 'guest' };

const body = <S extends z.ZodType>(req: Request): z.infer<S> =>
  (req.validated as { body: z.infer<S> }).body;

const presignData = (
  p: Awaited<ReturnType<UploadsService['presign']>>,
): Record<string, unknown> => ({
  key: p.key,
  maxBytes: p.maxBytes,
  upload: {
    url: p.upload.url,
    method: p.upload.method,
    headers: p.upload.headers,
    expiresAt: p.upload.expiresAt.toISOString(),
  },
});

/** Presign + confirm for one namespace. Keys are generated by the server, never by the client. */
export const createUploadsRouter = ({
  service,
  guard,
  actorOf,
  limiter,
  guestLicense = false,
}: UploadsRouterOptions): Router => {
  const router = Router();
  const routes = UPLOAD_ROUTES;
  router.post(
    routes.presign,
    ...guard,
    validate({ body: presignSchema }),
    asyncHandler(async (req: Request, res: Response) => {
      const input = body<typeof presignSchema>(req);
      sendSuccess(req, res, {
        data: presignData(await service.presign({ ...input, actor: actorOf(req) })),
      });
    }),
  );
  router.post(
    routes.confirm,
    ...guard,
    validate({ body: confirmSchema }),
    asyncHandler(async (req: Request, res: Response) => {
      const { key } = body<typeof confirmSchema>(req);
      sendSuccess(req, res, { data: await service.confirm({ key, actor: actorOf(req) }) });
    }),
  );
  if (guestLicense) {
    router.post(
      routes.licensePresign,
      limiter,
      validate({ body: licensePresignSchema }),
      asyncHandler(async (req: Request, res: Response) => {
        const input = body<typeof licensePresignSchema>(req);
        const result = await service.presign({ ...input, actor: GUEST });
        sendSuccess(req, res, { data: presignData(result) });
      }),
    );
    router.post(
      routes.licenseConfirm,
      limiter,
      validate({ body: confirmSchema }),
      asyncHandler(async (req: Request, res: Response) => {
        const { key } = body<typeof confirmSchema>(req);
        sendSuccess(req, res, { data: await service.confirm({ key, actor: GUEST }) });
      }),
    );
  }
  return router;
};
