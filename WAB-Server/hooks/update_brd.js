/**
 * update_brd — Hook: Regenerate BRD.md from manifest + source code.
 *
 * Usage:  node hooks/update_brd.js
 * Effect: Reads hooks/config/api-manifest.json + src/models/*.model.js →
 *         rewrites BRD.md with current state
 */

const fs = require('fs');
const path = require('path');

const manifestPath = path.resolve(__dirname, 'config', 'api-manifest.json');
const brdPath = path.resolve(__dirname, '..', 'BRD.md');
const modelsDir = path.resolve(__dirname, '..', 'src', 'models');

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));

const extractModelFields = (filePath) => {
  const content = fs.readFileSync(filePath, 'utf-8');
  const nameMatch = filePath.match(/(\w+)\.model\.js$/);
  if (!nameMatch) return null;
  const modelName = nameMatch[1];

  const fields = [];
  const fieldRegex = /(\w+):\s*\{\s*\n\s*type:\s*(\w+)/g;
  let match;
  while ((match = fieldRegex.exec(content)) !== null) {
    const required = content.slice(match.index, match.index + 200).includes('required: true');
    const defaultValue = content.slice(match.index, match.index + 200).match(/default:\s*(\S+)/);
    fields.push({
      name: match[1],
      type: match[2],
      required,
      default: defaultValue ? defaultValue[1].replace(/,.*/, '') : null,
    });
  }
  return { modelName, fields };
};

const models = [];
if (fs.existsSync(modelsDir)) {
  const files = fs.readdirSync(modelsDir).filter((f) => f.endsWith('.model.js'));
  for (const file of files) {
    const result = extractModelFields(path.join(modelsDir, file));
    if (result) models.push(result);
  }
}

